#!/usr/bin/env python3
"""Generate one tensor-core test per WMMA variant: wmma_<variant>.cu

Each test runs D = A*B + C on one tile with A = B = identity-like and C = 0, then poisons element
[0,0] of A, B, C with a few (a, b, c) cases and launches one warp per case (same idea as basic.cu).
Variants follow examples/mma-examples/extractmmas.py. Regenerate with `make gen` (from test/).
The generated files are checked in; edit this script, not them.
"""
# name: (M, N, K, Td, Ta, Tc, include, a/b host type, cases (a, b, c) as C expressions, min_sm, note)
INF = "INFINITY"
VARIANTS = {
    "f16_f32acc": dict(M=16, N=16, K=16, Ta="half", Tc="float", frag_a="half", conv="__float2half",
                       inc="#include <cuda_fp16.h>", sm=80,
                       cases=[("1.0f", "1.0f", INF), (INF, "1.0f", "-" + INF), ("65504.0f", "65504.0f", "0.0f")],
                       note="HMMA.16816.F32 (FP16 inputs, FP32 accumulate). 65504^2 does not overflow in FP32."),
    "bf16_f32acc": dict(M=16, N=16, K=16, Ta="__nv_bfloat16", Tc="float", frag_a="__nv_bfloat16",
                        conv="__float2bfloat16", inc="#include <cuda_bf16.h>", sm=80,
                        cases=[("3.0e38f", "3.0e38f", "0.0f"), (INF, "1.0f", "-" + INF), ("1.0f", "1.0f", INF)],
                        note="HMMA.16816.F32.BF16 (BF16 inputs, FP32 accumulate). 3e38^2 overflows FP32."),
    "tf32": dict(M=16, N=16, K=8, Ta="float", Tc="float", frag_a="wmma::precision::tf32", tf32=True,
                 conv="", inc="", sm=80,
                 cases=[("3.0e38f", "3.0e38f", "0.0f"), (INF, "1.0f", "-" + INF), ("1.17549435e-38f", "0.5f", "0.0f")],
                 note="HMMA.1684.F32.TF32. FLT_MIN * 0.5 is a subnormal product."),
    "f64": dict(M=8, N=8, K=4, Ta="double", Tc="double", frag_a="double", conv="", inc="", sm=80,
                cases=[("1.0e308", "10.0", "0.0"), (INF, "1.0", "-" + INF), ("2.2250738585072014e-308", "0.5", "0.0")],
                note="FP64 WMMA 8x8x4 (DMMA on GPUs that have it)."),
}

TEMPLATE = r'''// GENERATED by gen_wmma_tests.py -- do not edit; edit the generator and run `make gen`.
#include <cstdio>
#include <cmath>
#include <cuda_runtime.h>
#include <mma.h>
{inc}
using namespace nvcuda;

// @min_sm {sm}

// {note}
// Shape m{M}n{N}k{K}; A and B are identity-like, C = 0; element [0,0] of each is overwritten per case.

__global__ void tile({Ta}* A, {Ta}* B, {Tc}* C, {Tc}* D) {{
    wmma::fragment<wmma::matrix_a, {M}, {N}, {K}, {frag_a}, wmma::row_major> a;
    wmma::fragment<wmma::matrix_b, {M}, {N}, {K}, {frag_a}, wmma::col_major> b;
    wmma::fragment<wmma::accumulator, {M}, {N}, {K}, {Tc}> c;
    wmma::load_matrix_sync(a, A, {K});
    wmma::load_matrix_sync(b, B, {K});
    wmma::load_matrix_sync(c, C, {N}, wmma::mem_row_major);
{tf32conv}    wmma::mma_sync(c, a, b, c);
    wmma::store_matrix_sync(D, c, {N}, wmma::mem_row_major);
}}

int main() {{
    {Ta} *A, *B; {Tc} *C, *D;
    cudaMallocManaged(&A, sizeof({Ta}) * {M} * {K});
    cudaMallocManaged(&B, sizeof({Ta}) * {K} * {N});
    cudaMallocManaged(&C, sizeof({Tc}) * {M} * {N});
    cudaMallocManaged(&D, sizeof({Tc}) * {M} * {N});
    const double cases[][3] = {{ {cases} }};
    for (auto& cs : cases) {{
        for (int i = 0; i < {M}; i++) for (int j = 0; j < {K}; j++) A[i * {K} + j] = {conv}(i == j ? 1.0f : 0.0f);
        for (int k = 0; k < {K}; k++) for (int n = 0; n < {N}; n++) B[n * {K} + k] = {conv}(k == n ? 1.0f : 0.0f);
        for (int i = 0; i < {M} * {N}; i++) C[i] = 0;
        A[0] = {conv}(cs[0]); B[0] = {conv}(cs[1]); C[0] = cs[2];
        tile<<<1, 32>>>(A, B, C, D);
        cudaDeviceSynchronize();
        printf("A00=%g B00=%g C00=%g -> D00=%g\n", cs[0], cs[1], cs[2], (double)D[0]);
    }}
    return 0;
}}
'''

for name, v in VARIANTS.items():
    cs = ", ".join("{%s, %s, %s}" % c for c in v.pop("cases"))
    if v["conv"] == "":
        v["conv"] = ""   # plain assignment: "(x)" is a harmless cast-free expression
    tf = ("    for (int i = 0; i < a.num_elements; i++) a.x[i] = wmma::__float_to_tf32(a.x[i]);\n"
          "    for (int i = 0; i < b.num_elements; i++) b.x[i] = wmma::__float_to_tf32(b.x[i]);\n") if v.get("tf32") else ""
    src = TEMPLATE.format(cases=cs, tf32conv=tf, **v)
    with open("wmma_%s.cu" % name, "w") as f:
        f.write(src)
    print("wrote wmma_%s.cu" % name)
